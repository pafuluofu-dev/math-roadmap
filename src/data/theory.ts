function toQuestions(texts: string[], source: TheorySource, offset: number): TheoryQuestion[] {
  const group = THEORY_GROUPS.find((candidate) => candidate.source === source)?.title ?? ''
  return texts.map((text, index) => ({
    id: `q${String(offset + index + 1).padStart(2, '0')}`,
    group,
    text,
    source,
  }))
}

